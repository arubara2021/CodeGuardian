"""C language plugin.

Ships at ``best-effort`` reliability. The kernel does not walk C
declarator chains when extracting a function's name, so C free
functions produce no symbols and cannot be the target of a resolved
call edge. The gap is G-15 in BUILD_STATE; when it closes, this plugin
moves to ``high``.
"""

from __future__ import annotations

from pathlib import Path

from codeguardian.core.errors import CodeGuardianError, ErrorCode, translate
from codeguardian.interfaces import SandboxHandle, TestResult

_EXTENSIONS = (".c", ".h")


class CPlugin:
    """Language plugin for C source files."""

    name = "c"
    tree_sitter_grammar = "tree-sitter-c"
    test_runner = "make test"
    refactor_rules = ("extract_function", "rename_symbol")
    reliability_tier = "best-effort"
    blast_scope = "same-file"
    kernel_extensible = False

    __manifest__ = {
        "name": "c",
        "version": "1.0.0",
        "type": "language",
        "interface_version": "1.0",
        "description": "C language support (best-effort; see G-15).",
        "capabilities": ["pointers", "preprocessor"],
        "language": {
            "name": "c",
            "tree_sitter_grammar": "tree-sitter-c",
            "test_runner": "make test",
            "refactor_rules": ["extract_function", "rename_symbol"],
            "reliability_tier": "best-effort",
            "blast_scope": "same-file",
            "kernel_extensible": False,
        },
        "permissions": {
            "filesystem": "read_only",
            "network": False,
            "process_spawn": False,
        },
    }

    def detect(self, path: Path) -> bool:
        return path.suffix in _EXTENSIONS

    def parse(self, path: Path) -> object:
        from codeguardian import _native

        try:
            source = path.read_text(encoding="utf-8")
        except OSError as exc:
            raise translate(exc) from exc
        try:
            return _native.build_graph([(str(path), self.name, source)])
        except Exception as exc:
            raise CodeGuardianError(
                ErrorCode.SYS_INTERNAL,
                f"failed to parse {path}: {exc}",
                details={"path": str(path), "plugin": self.name},
            ) from exc

    def generate_test(self, context: object) -> str:
        return (
            "/* Characterization test scaffold for C. */\n"
            "/* Generated by codeguardian.plugins_bundled.languages.c. */\n"
            "/* The Tester agent (Phase 11) replaces the skip with concrete\n"
            "   assertions derived from the target function. */\n"
            "#include <assert.h>\n"
            "\n"
            "int main(void) {\n"
            "    /* assertions populated by the Tester agent */\n"
            "    return 0;\n"
            "}\n"
        )

    def run_tests(self, sandbox: SandboxHandle, test_path: str) -> TestResult:
        raise CodeGuardianError(
            ErrorCode.SYS_NOT_IMPLEMENTED,
            "language plugin run_tests is wired in Phase 11; the Tester "
            "agent owns test execution and holds the sandbox backend",
            details={"plugin": self.name, "test_path": test_path},
        )
