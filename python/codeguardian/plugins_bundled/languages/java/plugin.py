"""Java language plugin."""

from __future__ import annotations

from pathlib import Path

from codeguardian.core.errors import CodeGuardianError, ErrorCode, translate
from codeguardian.interfaces import SandboxHandle, TestResult


class JavaPlugin:
    """Language plugin for Java source files."""

    name = "java"
    tree_sitter_grammar = "tree-sitter-java"
    test_runner = "junit"
    refactor_rules = ("extract_method", "extract_interface", "rename_symbol")
    reliability_tier = "best-effort"
    blast_scope = "same-file"
    kernel_extensible = False

    __manifest__ = {
        "name": "java",
        "version": "1.0.0",
        "type": "language",
        "interface_version": "1.0",
        "description": "Java language support.",
        "capabilities": ["generics", "annotations", "classes", "interfaces"],
        "language": {
            "name": "java",
            "tree_sitter_grammar": "tree-sitter-java",
            "test_runner": "junit",
            "refactor_rules": [
                "extract_method",
                "extract_interface",
                "rename_symbol",
            ],
            "reliability_tier": "best-effort",
            "blast_scope": "same-file",
            "kernel_extensible": False,
        },
        "permissions": {
            "filesystem": "read_only",
            "network": False,
            "process_spawn": False,
        },
    }

    def detect(self, path: Path) -> bool:
        return path.suffix == ".java"

    def parse(self, path: Path) -> object:
        from codeguardian import _native

        try:
            source = path.read_text(encoding="utf-8")
        except OSError as exc:
            raise translate(exc) from exc
        try:
            return _native.build_graph([(str(path), self.name, source)])
        except Exception as exc:
            raise CodeGuardianError(
                ErrorCode.SYS_INTERNAL,
                f"failed to parse {path}: {exc}",
                details={"path": str(path), "plugin": self.name},
            ) from exc

    def generate_test(self, context: object) -> str:
        return (
            "// Characterization test scaffold for Java (JUnit 5).\n"
            "// Generated by codeguardian.plugins_bundled.languages.java.\n"
            "// The Tester agent (Phase 11) replaces the disabled test with\n"
            "// concrete assertions derived from the target method.\n"
            "import org.junit.jupiter.api.Disabled;\n"
            "import org.junit.jupiter.api.Test;\n"
            "\n"
            "class CharacterizationTest {\n"
            "    @Test\n"
            '    @Disabled("populated by the Tester agent")\n'
            "    void characterization() {\n"
            "    }\n"
            "}\n"
        )

    def run_tests(self, sandbox: SandboxHandle, test_path: str) -> TestResult:
        raise CodeGuardianError(
            ErrorCode.SYS_NOT_IMPLEMENTED,
            "language plugin run_tests is wired in Phase 11; the Tester "
            "agent owns test execution and holds the sandbox backend",
            details={"plugin": self.name, "test_path": test_path},
        )
