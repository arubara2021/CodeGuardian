"""JavaScript language plugin."""

from __future__ import annotations

from pathlib import Path

from codeguardian.core.errors import CodeGuardianError, ErrorCode, translate
from codeguardian.interfaces import SandboxHandle, TestResult

_EXTENSIONS = (".js", ".mjs", ".cjs", ".jsx")


class JavaScriptPlugin:
    """Language plugin for JavaScript source files."""

    name = "javascript"
    tree_sitter_grammar = "tree-sitter-javascript"
    test_runner = "vitest"
    refactor_rules = ("extract_function", "convert_to_arrow", "rename_symbol")
    reliability_tier = "best-effort"
    blast_scope = "same-file"
    kernel_extensible = False

    __manifest__ = {
        "name": "javascript",
        "version": "1.0.0",
        "type": "language",
        "interface_version": "1.0",
        "description": "JavaScript language support.",
        "capabilities": ["async", "generators", "classes", "modules"],
        "language": {
            "name": "javascript",
            "tree_sitter_grammar": "tree-sitter-javascript",
            "test_runner": "vitest",
            "refactor_rules": [
                "extract_function",
                "convert_to_arrow",
                "rename_symbol",
            ],
            "reliability_tier": "best-effort",
            "blast_scope": "same-file",
            "kernel_extensible": False,
        },
        "permissions": {
            "filesystem": "read_only",
            "network": False,
            "process_spawn": False,
        },
    }

    def detect(self, path: Path) -> bool:
        return path.suffix in _EXTENSIONS

    def parse(self, path: Path) -> object:
        from codeguardian import _native

        try:
            source = path.read_text(encoding="utf-8")
        except OSError as exc:
            raise translate(exc) from exc
        try:
            return _native.build_graph([(str(path), self.name, source)])
        except Exception as exc:
            raise CodeGuardianError(
                ErrorCode.SYS_INTERNAL,
                f"failed to parse {path}: {exc}",
                details={"path": str(path), "plugin": self.name},
            ) from exc

    def generate_test(self, context: object) -> str:
        return (
            "// Characterization test scaffold for JavaScript.\n"
            "// Generated by codeguardian.plugins_bundled.languages.javascript.\n"
            "// The Tester agent (Phase 11) replaces the skip body with\n"
            "// concrete assertions derived from the target function.\n"
            'import { describe, it } from "vitest";\n'
            "\n"
            'describe("characterization", () => {\n'
            '  it.skip("populated by the Tester agent", () => {\n'
            "    // assertions added in Phase 11\n"
            "  });\n"
            "});\n"
        )

    def run_tests(self, sandbox: SandboxHandle, test_path: str) -> TestResult:
        raise CodeGuardianError(
            ErrorCode.SYS_NOT_IMPLEMENTED,
            "language plugin run_tests is wired in Phase 11; the Tester "
            "agent owns test execution and holds the sandbox backend",
            details={"plugin": self.name, "test_path": test_path},
        )
