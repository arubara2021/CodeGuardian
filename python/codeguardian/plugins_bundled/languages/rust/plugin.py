"""Rust language plugin."""

from __future__ import annotations

from pathlib import Path

from codeguardian.core.errors import CodeGuardianError, ErrorCode, translate
from codeguardian.interfaces import SandboxHandle, TestResult


class RustPlugin:
    """Language plugin for Rust source files."""

    name = "rust"
    tree_sitter_grammar = "tree-sitter-rust"
    test_runner = "cargo test"
    refactor_rules = ("extract_function", "extract_trait", "rename_symbol")
    reliability_tier = "high"
    blast_scope = "same-file"
    kernel_extensible = False

    __manifest__ = {
        "name": "rust",
        "version": "1.0.0",
        "type": "language",
        "interface_version": "1.0",
        "description": "Rust language support.",
        "capabilities": ["generics", "traits", "macros", "lifetimes"],
        "language": {
            "name": "rust",
            "tree_sitter_grammar": "tree-sitter-rust",
            "test_runner": "cargo test",
            "refactor_rules": [
                "extract_function",
                "extract_trait",
                "rename_symbol",
            ],
            "reliability_tier": "high",
            "blast_scope": "same-file",
            "kernel_extensible": False,
        },
        "permissions": {
            "filesystem": "read_only",
            "network": False,
            "process_spawn": False,
        },
    }

    def detect(self, path: Path) -> bool:
        return path.suffix == ".rs"

    def parse(self, path: Path) -> object:
        from codeguardian import _native

        try:
            source = path.read_text(encoding="utf-8")
        except OSError as exc:
            raise translate(exc) from exc
        try:
            return _native.build_graph([(str(path), self.name, source)])
        except Exception as exc:
            raise CodeGuardianError(
                ErrorCode.SYS_INTERNAL,
                f"failed to parse {path}: {exc}",
                details={"path": str(path), "plugin": self.name},
            ) from exc

    def generate_test(self, context: object) -> str:
        return (
            "// Characterization test scaffold for Rust.\n"
            "// Generated by codeguardian.plugins_bundled.languages.rust.\n"
            "// The Tester agent (Phase 11) replaces the ignore attribute\n"
            "// with concrete assertions derived from the target function.\n"
            "#[cfg(test)]\n"
            "mod characterization {\n"
            "    use super::*;\n"
            "\n"
            "    #[test]\n"
            '    #[ignore = "populated by the Tester agent"]\n'
            "    fn characterization() {\n"
            "    }\n"
            "}\n"
        )

    def run_tests(self, sandbox: SandboxHandle, test_path: str) -> TestResult:
        raise CodeGuardianError(
            ErrorCode.SYS_NOT_IMPLEMENTED,
            "language plugin run_tests is wired in Phase 11; the Tester "
            "agent owns test execution and holds the sandbox backend",
            details={"plugin": self.name, "test_path": test_path},
        )
