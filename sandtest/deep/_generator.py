"""Deterministic execution records for candidate targets.

The pipeline needs one fact per candidate: what does the function
return when called with the sample arguments that discovery
synthesized? That fact, recorded as a normalized JSON value, is what
the tool's characterization test asserts on the old code and again on
the new code. A candidate whose execution errors, or whose return is
not deterministic across two calls, is still discovered and ranked;
the caller decides whether to run the pipeline on it.

The execution happens inside the network-OFF sandbox. The generator
is a standalone Python script written into the clone, executed with
the clone root on `sys.path`, and its output is read back on the
host. The script imports each candidate module, calls each function
twice, normalizes both values, and records the result.

Three functions, one concern each:

- `write_generator_artifacts` writes the manifest and generator
  script into the clone.
- `run_generator` executes the generator inside the sandbox.
- `read_generator_results` reads the resulting JSON into an execution
  map keyed by `(module, function)`.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import TYPE_CHECKING, Any

from ._discovery import RankedTarget
from ._preflight import CheckResult

if TYPE_CHECKING:
    from ._sandbox import SandboxSession

__all__ = [
    "execution_map",
    "read_generator_results",
    "run_generator",
    "write_generator_artifacts",
]


GENERATOR_FILENAME = "deep_test_generator.py"
MANIFEST_FILENAME = "deep_test_manifest.json"
RESULTS_FILENAME = "deep_test_targets.json"


_GENERATOR_SCRIPT = r'''"""Auto-generated by CodeGuardian's deep test."""
import importlib
import json
import os
import sys
from pathlib import Path

_root = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _root)
_deps = os.path.join(_root, ".deps")
if os.path.isdir(_deps):
    sys.path.insert(0, _deps)
if os.path.isdir(os.path.join(_root, "src")):
    sys.path.insert(0, os.path.join(_root, "src"))


def normalize(value):
    if value is None or isinstance(value, bool):
        return {"t": type(value).__name__, "v": value}
    if isinstance(value, int):
        return {"t": "int", "v": value}
    if isinstance(value, float):
        if value != value:
            return {"t": "float", "v": "nan"}
        if value == float("inf"):
            return {"t": "float", "v": "inf"}
        if value == float("-inf"):
            return {"t": "float", "v": "-inf"}
        return {"t": "float", "v": value}
    if isinstance(value, str):
        return {"t": "str", "v": value}
    if isinstance(value, bytes):
        return {
            "t": "bytes",
            "len": len(value),
            "sha256_16": __import__("hashlib").sha256(value).hexdigest()[:16],
        }
    if isinstance(value, dict):
        items = sorted(
            ([str(k), normalize(v)] for k, v in value.items()),
            key=lambda kv: kv[0],
        )
        return {"t": "dict", "items": items}
    if isinstance(value, (list, tuple)):
        return {"t": type(value).__name__, "items": [normalize(v) for v in value]}
    if isinstance(value, (set, frozenset)):
        items = sorted((normalize(v) for v in value), key=repr)
        return {"t": type(value).__name__, "items": items}
    if hasattr(value, "__dataclass_fields__"):
        from dataclasses import asdict
        return {"t": type(value).__name__, "dataclass": normalize(asdict(value))}
    if hasattr(value, "__dict__"):
        public = {k: v for k, v in vars(value).items() if not k.startswith("_")}
        return {"t": type(value).__name__, "attrs": normalize(public)}
    return {"t": type(value).__name__, "repr": repr(value)[:200]}


def main():
    manifest = json.loads(Path("deep_test_manifest.json").read_text())
    results = []
    for item in manifest:
        record = {
            "module": item["module"],
            "function": item["function"],
            "args": item["args"],
        }
        try:
            module = importlib.import_module(item["module"])
            func = getattr(module, item["function"])
        except Exception as exc:
            record["error"] = f"import failed: {type(exc).__name__}: {exc}"
            results.append(record)
            continue
        try:
            first = func(*item["args"])
        except Exception as exc:
            record["error"] = f"call raised: {type(exc).__name__}: {exc}"
            results.append(record)
            continue
        try:
            second = func(*item["args"])
        except Exception as exc:
            record["error"] = f"second call raised: {type(exc).__name__}: {exc}"
            results.append(record)
            continue
        n1 = normalize(first)
        n2 = normalize(second)
        record["deterministic"] = (n1 == n2)
        record["expected_type"] = type(first).__name__
        record["expected_value_json"] = json.dumps(n1)
        results.append(record)
    Path("deep_test_targets.json").write_text(json.dumps(results, indent=2))


if __name__ == "__main__":
    main()
'''


def write_generator_artifacts(clone_root: Path, targets: list[RankedTarget]) -> Path:
    """Write the generator script and manifest into the clone.

    Args:
        clone_root: The cloned repository root.
        targets: The ranked targets to include. Every one is written
            to the manifest; a target whose function raises during the
            generator's run records the error, and the caller decides
            whether to use it.

    Returns:
        The path to the manifest, for logging.
    """
    manifest = [
        {
            "module": t.candidate.module,
            "function": t.candidate.function,
            "args": list(t.candidate.args),
        }
        for t in targets
    ]
    manifest_path = Path(clone_root) / MANIFEST_FILENAME
    manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    (Path(clone_root) / GENERATOR_FILENAME).write_text(_GENERATOR_SCRIPT, encoding="utf-8")
    return manifest_path


def run_generator(
    session: SandboxSession,
    clone_root: Path,
    *,
    timeout_ms: int = 120_000,
) -> CheckResult:
    """Execute the generator script inside the sandbox.

    The script reads the manifest, imports each module, calls each
    function, and writes the results JSON. The launcher is not
    required (the generator imports no test library), so the runner
    uses the plain interpreter. The clone's ``.deps`` directory is on
    ``PYTHONPATH`` and inside the script's own ``sys.path`` setup, so
    a candidate function that imports a third-party package installed
    by the repository's install commands can reach it. Without this,
    the generator fails with ``ModuleNotFoundError`` for any
    repository whose candidate functions import a dependency.

    Args:
        session: An active network-OFF sandbox session.
        clone_root: The cloned repository root. Passed to the session
            as the working directory ``"clone"`` so the script's
            relative manifest and results paths resolve correctly.
        timeout_ms: Wall-clock budget.

    Returns:
        A ``CheckResult``. The caller records it; a failed generator
        is not a fatal error but means the pipeline has no targets to
        work on.
    """
    del clone_root  # the sandbox's cwd is already the clone root
    result = session.run(
        "PYTHONPATH=.deps:.:$PYTHONPATH python3 deep_test_generator.py",
        cwd="clone",
        timeout_ms=timeout_ms,
    )
    if result.exit_code == 0:
        return CheckResult("generator ran", True, "exit=0")
    stderr_tail = (result.stderr or "").strip().splitlines()[-3:]
    return CheckResult(
        "generator ran",
        False,
        f"exit={result.exit_code}" + (" | " + " / ".join(stderr_tail) if stderr_tail else ""),
    )


def read_generator_results(clone_root: Path) -> list[dict[str, Any]]:
    """Read the results JSON that the generator wrote.

    Args:
        clone_root: The cloned repository root.

    Returns:
        The list of record dictionaries. An empty list when the file
        is missing or unparseable; the caller decides whether that is
        a hard failure or a soft skip.
    """
    path = Path(clone_root) / RESULTS_FILENAME
    if not path.is_file():
        return []
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return []
    return data if isinstance(data, list) else []


def execution_map(
    results: list[dict[str, Any]],
) -> dict[tuple[str, str], dict[str, Any]]:
    """Build the execution map keyed by ``(module, function)``.

    Args:
        results: The list returned by ``read_generator_results``.

    Returns:
        A mapping from each ``(module, function)`` pair to its
        record. Records missing either key are dropped; the pipeline
        treats a missing record as "not executed", which is the same
        state as a target the generator never saw.
    """
    mapping: dict[tuple[str, str], dict[str, Any]] = {}
    for record in results:
        module = record.get("module")
        function = record.get("function")
        if isinstance(module, str) and isinstance(function, str):
            mapping[(module, function)] = record
    return mapping
